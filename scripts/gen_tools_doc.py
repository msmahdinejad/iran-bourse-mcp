"""Regenerate docs/TOOLS.md from the live tool registry so the docs cannot drift.

    uv run python scripts/gen_tools_doc.py
"""

from __future__ import annotations

import asyncio
from pathlib import Path

from tool_groups import GROUPS

from iran_bourse_mcp.server import mcp


def schema_of(tool) -> dict:
    return getattr(tool, "inputSchema", None) or tool.input_schema


async def main() -> None:
    tools = {t.name: t for t in await mcp.list_tools()}
    lines = ["# Tool reference", "", "_Generated by `scripts/gen_tools_doc.py`. All tools are read-only._", ""]
    for group, names in GROUPS.items():
        lines += [f"## {group}", ""]
        for name in names:
            tool = tools[name]
            props = schema_of(tool).get("properties", {})
            required = set(schema_of(tool).get("required", []))
            lines += [f"### `{name}`", "", (tool.description or "").strip(), ""]
            if props:
                lines += ["| parameter | type | description |", "|---|---|---|"]
                for pname, spec in props.items():
                    kind = spec.get("type") or "/".join(x.get("type", "?") for x in spec.get("anyOf", []) if x.get("type") != "null") or "any"
                    star = "*" if pname in required else ""
                    desc = (spec.get("description") or "").replace("|", "\\|")
                    default = f" (default `{spec['default']}`)" if "default" in spec and spec["default"] is not None else ""
                    lines.append(f"| `{pname}`{star} | {kind} | {desc}{default} |")
                lines.append("")
    missing = set(tools) - {n for names in GROUPS.values() for n in names}
    assert not missing, f"tools missing from GROUPS: {missing}"
    out = Path(__file__).resolve().parent.parent / "docs" / "TOOLS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(tools)} tools)")


if __name__ == "__main__":
    asyncio.run(main())
